def parse_route(text: str | None) -> str | None:
    if not text:
        return None
    t = " " + text.lower() + " "
    for k in sorted(ROUTES, key=len, reverse=True):
        if re.search(rf"(?<![a-z]){re.escape(k)}(?![a-z])", t):
            return ROUTES[k]
    return None


