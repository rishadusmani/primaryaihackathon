def lookup_vaccine(text: str | None = None, cvx: str | None = None) -> dict | None:
    for name, (code, syns) in VACCINES.items():
        if cvx and cvx.strip() == code:
            return {"vaccine": name, "cvx": code}
        if text and any(re.search(rf"\b{re.escape(s)}\b", text.lower()) for s in syns):
            return {"vaccine": name, "cvx": code}
    return None


def find_vaccines(text: str) -> list[tuple[dict, int]]:
    """Every vaccine named in `text`, with the position of its match, in table order.
    A span claimed by an earlier (more specific) entry isn't reused ("MMRV" is not also "MMR")."""
    low, out, taken = text.lower(), [], []
    for name, (code, syns) in VACCINES.items():
        for s in sorted(syns, key=len, reverse=True):
            m = next((m for m in re.finditer(rf"(?<![a-z0-9]){re.escape(s)}(?![a-z0-9])", low)
                      if not any(a <= m.start() < b for a, b in taken)), None)
            if m:
                taken.append((m.start(), m.end()))
                out.append(({"vaccine": name, "cvx": code, "phrase": s}, m.start()))
                break
    return out


