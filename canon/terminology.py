def _load_vocab(name: str) -> list[dict]:
    with open(_VOCAB_DIR / name, encoding="utf-8") as fh:
        return json.load(fh)


def _index(names: list[str], exact: list[str], target: str, scan: dict, exact_index: dict) -> None:
    exact_keys = {_key(e) for e in exact}
    for n in names:
        k = _key(n)
        if k and k not in exact_keys:
            scan.setdefault(k, target)
    for n in [*exact, *names]:
        exact_index.setdefault(_key(n), target)


def _conv_rule(rule):
    if isinstance(rule, list):
        scale, offset = rule
        return lambda v: v * scale + offset
    return float(rule)


